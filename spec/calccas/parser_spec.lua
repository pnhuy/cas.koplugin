local parser = require("calccas.parser")
local sexp = require("spec.calccas.helpers").sexp

local function p(text, overrides)
  local node, err = parser.parse(text, overrides)
  assert.is_nil(err, err and tostring(err))
  return sexp(node)
end

local function perr(text, overrides)
  local node, err = parser.parse(text, overrides)
  assert.is_nil(node)
  assert.is_table(err)
  return err
end

describe("calccas.parser", function()
  describe("precedence", function()
    it("multiplies before adding", function() assert.are.equal("14", p("2 + 3*4")) end)
    it("unary minus binds looser than ^: -2^2 = -4", function() assert.are.equal("-4", p("-2^2")) end)
    it("^ is right-associative: 2^3^2 = 512", function() assert.are.equal("512", p("2^3^2")) end)
    it("allows a signed exponent", function() assert.are.equal("1/2", p("2^-1")) end)
    it("applies unary minus to the whole power: -x^2", function()
      assert.are.equal("(* -1 (^ x 2))", p("-x^2"))
    end)
    it("treats unary plus as a no-op", function() assert.are.equal("x", p("+x")) end)
    it("subtracts left to right", function() assert.are.equal("5", p("10-3-2")) end)
    it("divides left to right", function() assert.are.equal("1/6", p("1/2/3")) end)
  end)

  describe("exact arithmetic during parse", function()
    it("adds rationals exactly", function() assert.are.equal("1/2", p("1/3+1/6")) end)
    it("reads decimals exactly", function() assert.are.equal("1/2", p("0.25 + 1/4")) end)
    it("keeps division by zero for the evaluator", function()
      assert.are.equal("(* 1 (^ 0 -1))", p("1/0"))
    end)
    it("keeps overflowing powers for the evaluator", function()
      assert.are.equal("(^ 10 1000)", p("10^1000"))
    end)
    it("falls back to a float for numbers beyond 15 digits", function()
      local node = assert(parser.parse("123456789012345678901"))
      assert.is_true(node.approx)
    end)
    it("rejects numbers that overflow a double", function()
      assert.are.equal("overflow", perr("1" .. string.rep("0", 400)).kind)
    end)
  end)

  describe("symbols", function()
    it("builds variables and constants", function()
      assert.are.equal("(+ x y)", p("y + x"))
      assert.are.equal("(* pi x)", p("pi*x"))
      assert.are.equal("e", p("e"))
    end)
    it("reads multi-letter identifiers as one variable", function()
      assert.are.equal("xy", p("xy"))
    end)
    it("builds subtraction and division without sub/div nodes", function()
      assert.are.equal("(+ x (* -1 y))", p("x - y"))
      assert.are.equal("(* x (^ x -1))", p("x/x"))
    end)
  end)

  describe("functions", function()
    it("nests function calls", function() assert.are.equal("(sin (cos x))", p("sin(cos(x))")) end)
    it("stores ln as log", function() assert.are.equal("(log x)", p("ln(x)")) end)
    it("accepts every supported function", function()
      for _, f in ipairs({ "sin", "cos", "tan", "exp", "log", "sqrt", "abs" }) do
        assert.are.equal("(" .. f .. " x)", p(f .. "(x)"))
      end
    end)
    it("requires parentheses after a function name", function()
      local err = perr("sin x")
      assert.are.equal("syntax", err.kind)
      assert.are.equal(5, err.pos)
    end)
    it("rejects unknown functions", function()
      local err = perr("foo(2)")
      assert.are.equal("syntax", err.kind)
      assert.are.equal(1, err.pos)
    end)
  end)

  describe("implicit multiplication", function()
    it("is rejected after a number with the explicit form", function()
      assert.are.equal("missing `*`: write `2*x`", perr("2x").message)
      assert.are.equal("missing `*`: write `2*pi`", perr("2pi").message)
      assert.are.equal("missing `*`: write `2*(x+1)`", perr("2(x+1)").message)
    end)
    it("is rejected after a closing parenthesis", function()
      assert.are.equal("missing `*`: write `(x+1)*(x-1)`", perr("(x+1)(x-1)").message)
      assert.are.equal("missing `*`: write `(x+1)*3`", perr("(x+1)3").message)
    end)
    it("names only the nearest factor: 2x^2", function()
      assert.are.equal("missing `*`: write `2*x`", perr("2x^2").message)
    end)
    it("names the factor next to the gap: 1/2x", function()
      assert.are.equal("missing `*`: write `2*x`", perr("1/2x").message)
    end)
    it("does not apply between variables or after an identifier", function()
      assert.are.equal("syntax", perr("x 2").kind)
      assert.are.equal("syntax", perr("x(2)").kind)
    end)
    it("does not apply between two numbers", function()
      local err = perr("2 3")
      assert.are.equal("syntax", err.kind)
      assert.are.equal(3, err.pos)
    end)
  end)

  describe("syntax errors", function()
    it("reports the offending position: 2 +* 3 -> 4", function()
      local err = perr("2 +* 3")
      assert.are.equal("syntax", err.kind)
      assert.are.equal(4, err.pos)
    end)
    it("rejects empty and blank input", function()
      assert.are.equal(1, perr("").pos)
      assert.are.equal("syntax", perr("   ").kind)
    end)
    it("reports an unclosed parenthesis at the end", function()
      local err = perr("(1+2")
      assert.are.equal("syntax", err.kind)
      assert.are.equal(5, err.pos)
    end)
    it("reports a stray closing parenthesis", function()
      local err = perr("1+2)")
      assert.are.equal("syntax", err.kind)
      assert.are.equal(4, err.pos)
    end)
    it("reports a dangling operator", function()
      assert.are.equal(4, perr("1 +").pos)
    end)
    it("rejects a malformed number such as 1.2.3", function()
      assert.are.equal("syntax", perr("1.2.3").kind)
    end)
    it("never evaluates Lua: os.execute(\"x\") is a syntax error", function()
      assert.are.equal("syntax", perr('os.execute("x")').kind)
    end)
    it("rejects non-string input without throwing", function()
      assert.are.equal("syntax", perr(nil).kind)
      assert.are.equal("syntax", perr(42).kind)
    end)
  end)

  describe("limits", function()
    it("rejects text longer than 500 characters", function()
      assert.are.equal("too_complex", perr(string.rep("1+", 251)).kind)
    end)
    it("accepts exactly 500 characters", function()
      assert.is_table(parser.parse(string.rep("x+", 249) .. "xx"))
    end)
    it("rejects nesting deeper than 50", function()
      assert.are.equal("too_complex", perr(string.rep("(", 51) .. "x" .. string.rep(")", 51)).kind)
      assert.are.equal("too_complex", perr(string.rep("-", 60) .. "x").kind)
    end)
    it("accepts moderate nesting", function()
      assert.are.equal("x", p(string.rep("(", 40) .. "x" .. string.rep(")", 40)))
    end)
    it("rejects trees over the node limit", function()
      assert.are.equal("too_complex", perr("x+y+z+w", { max_nodes = 4 }).kind)
      assert.are.equal("(+ w x y z)", p("x+y+z+w", { max_nodes = 5 }))
    end)
    it("honours a tighter depth override", function()
      assert.are.equal("too_complex", perr("((((x))))", { max_depth = 3 }).kind)
    end)
  end)

  it("is deterministic", function()
    assert.are.equal(p("y*x + 2*x*y - 3"), p("y*x + 2*x*y - 3"))
  end)
end)
