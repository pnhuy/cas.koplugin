local parser = require("calccas.parser")
local printer = require("calccas.printer")
local ast = require("calccas.ast")

local function pr(text)
  return printer.tostring(assert(parser.parse(text)))
end

describe("calccas.printer", function()
  it("prints sums highest degree first with the constant last", function()
    assert.are.equal("x^2+2*x+1", pr("1 + 2*x + x^2"))
    assert.are.equal("x*y+x+y", pr("y + x + x*y"))
    assert.are.equal("-x+2", pr("2 - x"))
  end)

  it("prints subtraction and signs without spaces", function()
    assert.are.equal("x-y", pr("x - y"))
    assert.are.equal("x^2-1", pr("x^2 - 1"))
    assert.are.equal("-x", pr("-x"))
    assert.are.equal("-x^2", pr("-x^2"))
    assert.are.equal("-2*x^2", pr("-2*x^2"))
    assert.are.equal("-(x+1)", pr("-(x+1)"))
  end)

  it("prints products with *", function()
    assert.are.equal("2*x", pr("2x"))
    assert.are.equal("x*y", pr("y*x"))
    assert.are.equal("2*sin(x)", pr("2*sin(x)"))
    assert.are.equal("2*pi", pr("2pi"))
    assert.are.equal("(x-1)*(x+1)", pr("(x+1)(x-1)"))
  end)

  it("prints quotients with /", function()
    assert.are.equal("x/2", pr("x/2"))
    assert.are.equal("3*x/2", pr("3*x/2"))
    assert.are.equal("1/x", pr("1/x"))
    assert.are.equal("x/y", pr("x/y"))
    assert.are.equal("x/x", pr("x/x"))
    assert.are.equal("1/(x+1)", pr("1/(x+1)"))
    assert.are.equal("x/y^2", pr("x/y^2"))
    assert.are.equal("x/(y*z)", pr("x/(y*z)"))
    assert.are.equal("x/(2*y)", pr("x/(2*y)"))
    assert.are.equal("-1/x", pr("-1/x"))
    assert.are.equal("2/x", pr("2/x"))
  end)

  it("prints powers with minimal parentheses", function()
    assert.are.equal("x^2", pr("x^2"))
    assert.are.equal("(x+1)^2", pr("(x+1)^2"))
    assert.are.equal("sin(x)^2", pr("sin(x)^2"))
    assert.are.equal("2^x", pr("2^x"))
    assert.are.equal("(1/2)^x", pr("(1/2)^x"))
    assert.are.equal("x^(1/2)", pr("x^(1/2)"))
    assert.are.equal("x^(-1/2)", pr("x^(-1/2)"))
    assert.are.equal("x^y", pr("x^y"))
    assert.are.equal("(x^(1/2))^(1/3)", pr("(x^(1/2))^(1/3)"))
  end)

  it("prints functions and nested calls", function()
    assert.are.equal("sin(cos(x))", pr("sin(cos(x))"))
    assert.are.equal("log(x)", pr("ln(x)"))
    assert.are.equal("sqrt(x+1)", pr("sqrt(x+1)"))
  end)

  it("prints rationals and integers", function()
    assert.are.equal("1/2", pr("1/2"))
    assert.are.equal("-1/2", pr("-1/2"))
    assert.are.equal("14", pr("2+3*4"))
  end)

  it("round-trips: parse(print(ast)) equals ast", function()
    local samples = {
      "x^2+2*x+1", "x/2", "3*x/2", "x/(y*z)", "x/(2*y)", "-x^2", "-2*x^2", "(x+1)^2", "(x+1)*(x-1)",
      "sin(x)^2", "x^(1/2)", "x^(-1/2)", "2^x", "(1/2)^x", "1/(x+1)", "x/y^2", "-(x+1)",
      "x*y+x+y", "2*sin(x)+cos(x)/x", "exp(-x^2)", "(x^(1/2))^(1/3)", "-1/x", "1/0", "10^1000",
    }
    for _, s in ipairs(samples) do
      local node = assert(parser.parse(s))
      local again = assert(parser.parse(printer.tostring(node)))
      assert.is_true(ast.equal(node, again), s .. " -> " .. printer.tostring(node))
    end
  end)

  it("is deterministic", function()
    assert.are.equal(pr("y*x + 2*x*y - 3"), pr("y*x + 2*x*y - 3"))
    assert.are.equal(pr("y + x"), pr("x + y"))
  end)

  describe("format_number", function()
    it("uses 9 significant digits and trims noise", function()
      assert.are.equal("1.41421356", printer.format_number(math.sqrt(2)))
      assert.are.equal("0.3", printer.format_number(0.1 + 0.2))
      assert.are.equal("100", printer.format_number(100))
      assert.are.equal("-2.5", printer.format_number(-2.5))
      assert.are.equal("0.000123456789", printer.format_number(0.000123456789))
    end)
    it("prints zero without a sign and large values in exponent form", function()
      assert.are.equal("0", printer.format_number(-0.0))
      assert.are.equal("1e+20", printer.format_number(1e20))
    end)
  end)

  describe("result_text", function()
    it("shows only the exact form for exact numbers", function()
      assert.are.equal("1/2", printer.result_text({ exact = ast.num(1, 2), value = 0.5 }))
    end)
    it("appends the decimal for irrational exact forms", function()
      local node = assert(parser.parse("sqrt(2)"))
      assert.are.equal("sqrt(2) ≈ 1.41421356", printer.result_text({ exact = node, value = math.sqrt(2) }))
    end)
    it("shows just the decimal for approximate results", function()
      assert.are.equal("2.5", printer.result_text({ value = 2.5 }))
    end)
    it("shows the symbolic form when variables are free", function()
      local node = assert(parser.parse("2*x+1"))
      assert.are.equal("2*x+1", printer.result_text({ exact = node }))
    end)
  end)
end)
