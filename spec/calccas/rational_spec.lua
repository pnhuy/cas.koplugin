local R = require("calccas.rational")

describe("calccas.rational", function()
  it("normalizes sign and gcd", function()
    local r = R.new(2, -4)
    assert.are.same({ n = -1, d = 2 }, { n = r.n, d = r.d })
    r = R.new(6, 3)
    assert.are.same({ n = 2, d = 1 }, { n = r.n, d = r.d })
  end)

  it("rejects zero denominator", function()
    local r, kind = R.new(1, 0)
    assert.is_nil(r)
    assert.are.equal("div_by_zero", kind)
  end)

  it("adds, subtracts, multiplies, divides exactly", function()
    local third, sixth = R.new(1, 3), R.new(1, 6)
    local s = R.add(third, sixth)
    assert.are.same({ 1, 2 }, { s.n, s.d })
    local d = R.sub(third, sixth)
    assert.are.same({ 1, 6 }, { d.n, d.d })
    local m = R.mul(R.new(2, 3), R.new(3, 4))
    assert.are.same({ 1, 2 }, { m.n, m.d })
    local q = R.div(R.new(1, 2), R.new(1, 4))
    assert.are.same({ 2, 1 }, { q.n, q.d })
  end)

  it("division by zero returns nil and div_by_zero", function()
    local r, kind = R.div(R.new(1, 1), R.new(0, 1))
    assert.is_nil(r)
    assert.are.equal("div_by_zero", kind)
  end)

  it("raises to integer powers, including negative", function()
    local p = R.pow_int(R.new(2, 3), 3)
    assert.are.same({ 8, 27 }, { p.n, p.d })
    p = R.pow_int(R.new(2, 3), -2)
    assert.are.same({ 9, 4 }, { p.n, p.d })
    p = R.pow_int(R.new(-2, 1), 3)
    assert.are.same({ -8, 1 }, { p.n, p.d })
    local z, kind = R.pow_int(R.new(0, 1), -1)
    assert.is_nil(z)
    assert.are.equal("div_by_zero", kind)
  end)

  it("reports overflow past 2^53 instead of returning a wrong exact value", function()
    local big = R.new(2 ^ 52, 1)
    local r, kind = R.mul(big, R.new(4, 1))
    assert.is_nil(r)
    assert.are.equal("overflow", kind)
    r, kind = R.pow_int(R.new(10, 1), 1000)
    assert.is_nil(r)
    assert.are.equal("overflow", kind)
  end)

  it("parses decimal strings exactly", function()
    local r = R.from_decimal("0.25")
    assert.are.same({ 1, 4 }, { r.n, r.d })
    r = R.from_decimal("12")
    assert.are.same({ 12, 1 }, { r.n, r.d })
    r = R.from_decimal(".5")
    assert.are.same({ 1, 2 }, { r.n, r.d })
  end)

  it("compares and converts", function()
    assert.is_true(R.eq(R.new(1, 2), R.new(2, 4)))
    assert.is_true(R.lt(R.new(1, 3), R.new(1, 2)))
    assert.are.equal(0.5, R.to_number(R.new(1, 2)))
    assert.is_true(R.is_integer(R.new(4, 2)))
    assert.is_false(R.is_integer(R.new(1, 2)))
  end)

  it("computes exact square roots of perfect-square rationals only", function()
    local r = R.sqrt(R.new(9, 4))
    assert.are.same({ 3, 2 }, { r.n, r.d })
    assert.is_nil(R.sqrt(R.new(2, 1)))
    assert.is_nil(R.sqrt(R.new(-4, 1)))
  end)
end)
