local parser = require("calccas.parser")
local eval = require("calccas.eval")
local sexp = require("spec.calccas.helpers").sexp

local function ev(text, vars)
  local node = assert(parser.parse(text))
  local res, err = eval.evaluate(node, vars)
  assert.is_nil(err, err and tostring(err))
  return res
end

describe("calccas.eval evaluate", function()
  it("evaluates integer and rational arithmetic exactly", function()
    local r = ev("2 + 3*4")
    assert.are.equal("14", sexp(r.exact))
    assert.are.equal(14, r.value)
    r = ev("1/3 + 1/6")
    assert.are.equal("1/2", sexp(r.exact))
    assert.are.equal(0.5, r.value)
  end)

  it("keeps decimals exact", function()
    assert.are.equal("3/10", sexp(ev("0.1 + 0.2").exact))
  end)

  it("keeps irrational results symbolic with a float value", function()
    local r = ev("sqrt(2)")
    assert.are.equal("(sqrt 2)", sexp(r.exact))
    assert.is_true(math.abs(r.value - 1.4142135623731) < 1e-12)
  end)

  it("extracts exact roots of perfect-square rationals", function()
    assert.are.equal("3/2", sexp(ev("sqrt(9/4)").exact))
    assert.are.equal("2", sexp(ev("4^(1/2)").exact))
    assert.are.equal("8", sexp(ev("4^(3/2)").exact))
    assert.are.equal("(^ 2 1/2)", sexp(ev("2^(1/2)").exact))
  end)

  it("evaluates constants", function()
    assert.are.equal("pi", sexp(ev("pi").exact))
    assert.are.equal(math.pi, ev("pi").value)
    assert.are.equal(math.exp(1), ev("e").value)
    assert.is_true(math.abs(ev("2*pi").value - 2 * math.pi) < 1e-12)
  end)

  it("evaluates functions at exact points", function()
    assert.are.equal("3", sexp(ev("abs(-3)").exact))
    assert.are.equal("0", sexp(ev("sin(0)").exact))
    assert.are.equal("1", sexp(ev("cos(0)").exact))
    assert.are.equal("1", sexp(ev("exp(0)").exact))
    assert.are.equal("0", sexp(ev("log(1)").exact))
  end)

  it("evaluates functions numerically elsewhere", function()
    assert.is_true(math.abs(ev("sin(1)").value - math.sin(1)) < 1e-15)
    assert.is_true(math.abs(ev("ln(10)").value - math.log(10)) < 1e-15)
    assert.is_true(math.abs(ev("sin(pi/6)").value - 0.5) < 1e-12)
  end)

  it("falls back to an approximate result when exact numbers overflow", function()
    local r = ev("123456789012345678 * 10")
    assert.is_nil(r.exact)
    assert.is_true(math.abs(r.value - 1.23456789012345678e18) < 1e4)
  end)

  describe("variables", function()
    it("substitutes numbers, decimal strings and rational strings", function()
      assert.are.equal("10", sexp(ev("x^2 + 1", { x = 3 }).exact))
      assert.are.equal("5/4", sexp(ev("x^2 + 1", { x = "1/2" }).exact))
      assert.are.equal("5/4", sexp(ev("x^2 + 1", { x = "0.5" }).exact))
      assert.are.equal("5/4", sexp(ev("x^2 + 1", { x = 0.5 }).exact))
      assert.are.equal("-1/2", sexp(ev("x", { x = "-1/2" }).exact))
    end)

    it("substitutes several variables", function()
      assert.are.equal("11", sexp(ev("x*y + 2", { x = 3, y = 3 }).exact))
    end)

    it("leaves unbound variables symbolic and reports them", function()
      local r = ev("2*x + 1")
      assert.is_nil(r.value)
      assert.are.equal("(+ 1 (* 2 x))", sexp(r.exact))
      assert.are.same({ "x" }, r.free)
      r = ev("x + y", { x = 1 })
      assert.are.same({ "y" }, r.free)
    end)

    it("rejects invalid variable values", function()
      local res, err = eval.evaluate(assert(parser.parse("x")), { x = "abc" })
      assert.is_nil(res)
      assert.are.equal("syntax", err.kind)
      res, err = eval.evaluate(assert(parser.parse("x")), { x = 0 / 0 })
      assert.is_nil(res)
      assert.are.equal("domain", err.kind)
    end)
  end)

  it("reports free variables sorted and unique", function()
    assert.are.same({ "x", "y" }, eval.free_vars(assert(parser.parse("y*x + x + sin(y)"))))
    assert.are.same({}, eval.free_vars(assert(parser.parse("2+pi"))))
  end)
end)

describe("calccas.eval compile", function()
  local function fn(text, var)
    local f, err = eval.compile(assert(parser.parse(text)), var or "x")
    assert.is_nil(err, err and tostring(err))
    return f
  end

  it("builds a closure of one variable", function()
    local f = fn("x^2")
    assert.are.equal(9, f(3))
    assert.are.equal(4, f(-2))
    assert.are.equal(9, fn("t^2", "t")(3))
    assert.are.equal(5, fn("5")(123))
  end)

  it("returns nil at undefined points instead of raising", function()
    assert.is_nil(fn("1/x")(0))
    assert.is_nil(fn("sqrt(x)")(-1))
    assert.are.equal(2, fn("sqrt(x)")(4))
    assert.is_nil(fn("log(x)")(0))
    assert.is_nil(fn("log(x)")(-3))
    assert.are.equal(0, fn("log(x)")(1))
    assert.is_nil(fn("sin(x)/x")(0))
    assert.is_nil(fn("tan(x)")(math.pi / 2))
    assert.is_true(math.abs(fn("tan(x)")(0.5) - math.tan(0.5)) < 1e-15)
    assert.is_nil(fn("exp(x)")(1000))
    assert.is_nil(fn("x^x")(0))
    assert.is_nil(fn("x^x")(-0.5))
    assert.are.equal(-1, fn("x^x")(-1))
    assert.is_nil(fn("x^(1/2)")(-4))
  end)

  it("returns nil for non-finite input", function()
    local f = fn("x+1")
    assert.is_nil(f(math.huge))
    assert.is_nil(f(0 / 0))
  end)

  it("rejects other free variables", function()
    local f, err = eval.compile(assert(parser.parse("x + y")), "x")
    assert.is_nil(f)
    assert.are.equal("unbound_variable", err.kind)
  end)

  it("is repeatable and reentrant across calls", function()
    local f = fn("x*x + 1")
    assert.are.equal(f(2), f(2))
    assert.are.equal(5, f(2))
    assert.are.equal(10, f(3))
  end)
end)
