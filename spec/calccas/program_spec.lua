local ast = require("calccas.ast")
local calccas = require("calccas")
local parser = require("calccas.parser")
local printer = require("calccas.printer")

local function program(src, overrides)
  return assert(parser.parse_program(src, overrides))
end

describe("calccas.parser.parse_program", function()
  it("returns one entry per statement with line, position and source", function()
    local list = program("a = 1\n\n  b = a + 1 # note")
    assert.are.equal(2, #list)
    assert.are.equal(1, list[1].line)
    assert.are.equal(3, list[2].line)
    assert.are.equal("b = a + 1", list[2].src)
    assert.are.equal("a + 1", list[2].rhs_src)
    assert.are.equal(1, list[1].pos)
  end)

  it("recovers at the next line so one bad line does not hide the rest", function()
    local list = program("1 +* 2\nx + 1\n$\ny")
    assert.are.equal(4, #list)
    assert.is_truthy(list[1].err)
    assert.are.equal("(add 1 x)", ast.dump(list[2].node))
    assert.is_truthy(list[3].err)
    assert.are.equal(3, list[3].err.line)
    assert.are.equal("y", ast.dump(list[4].node))
  end)

  it("sees functions defined earlier in the cell and from the caller", function()
    local list = program("f(x) = x^2\nf(3)")
    assert.are.equal("9", ast.dump(list[2].node))
    local body = assert(calccas.parse("x+1"))
    local more = program("g(2)", { user_funcs = { g = { params = { "x" }, body = body } } })
    assert.are.equal("3", ast.dump(more[1].node))
  end)

  it("redefining a name as a variable hides the function", function()
    local list = program("f(x) = x\nf = 2\nf(3)")
    assert.is_truthy(list[3].err)
  end)

  it("measures the length limit per statement", function()
    local long = "a = " .. string.rep("1+", 300) .. "1"
    local list = program("b = 1\n" .. long)
    assert.is_nil(list[1].err)
    assert.are.equal("too_complex", list[2].err.kind)
  end)

  it("keeps argument sources of a top-level call", function()
    local list = program("plot(sin(x), cos(2*x), x=-1..1)")
    assert.are.same({ "sin(x)", "cos(2*x)", "x=-1..1" }, list[1].arg_srcs)
  end)

  it("parse() takes one expression and rejects statements", function()
    assert.is_nil(parser.parse("a = 1"))
    local _, err = parser.parse("a = 1")
    assert.are.equal("syntax", err.kind)
    assert.is_nil(parser.parse("1\n2"))
    assert.is_truthy(parser.parse("1 +\n2"))
  end)
end)

describe("scientific notation", function()
  local function dump(src)
    return ast.dump(assert(parser.parse(src)))
  end

  it("is exact when it fits", function()
    assert.are.equal("1000", dump("1e3"))
    assert.are.equal("1/1000", dump("1e-3"))
    assert.are.equal("1/400", dump("2.5e-3"))
    assert.are.equal("0", dump("0e500"))
  end)

  it("falls back to an approximate value beyond the exact range", function()
    assert.are.equal("~1e+30", dump("1e30"))
  end)

  it("reports overflow without building the power", function()
    local _, e1 = parser.parse("1e400")
    assert.are.equal("overflow", e1.kind)
    local _, e2 = parser.parse("1e-400")
    assert.are.equal("overflow", e2.kind)
    local _, e3 = parser.parse("1e99999999999999999999")
    assert.are.equal("overflow", e3.kind)
  end)

  it("keeps e a constant", function()
    assert.are.equal("(mul 2 e)", dump("2*e"))
    assert.are.equal("(mul 2 e)", dump("2 * e"))
  end)
end)

describe("relations", function()
  it("evaluate to a relation of the two sides, never a boolean", function()
    local r = assert(calccas.evaluate("x + 1 == 2*3"))
    assert.are.equal("x+1 == 6", r.text)
    assert.are.equal("rel", r.exact.t)
    assert.are.same({ "x" }, r.free)
    assert.are.equal("6 == 6", assert(calccas.evaluate("2*3 == 6")).text)
    assert.are.equal("1/2 == 1/2", assert(calccas.evaluate("0.5 == 1/2")).text)
  end)

  it("print with ==", function()
    local node = assert(parser.parse("x^2 == 4"))
    assert.are.equal("x^2 == 4", printer.tostring(node))
  end)

  it("are not accepted by simplify, expand or compile", function()
    local _, e1 = calccas.simplify("x == 1")
    assert.are.equal("unsupported", e1.kind)
    local _, e2 = calccas.expand("x == 1")
    assert.are.equal("unsupported", e2.kind)
    local _, e3 = calccas.compile("x == 1")
    assert.are.equal("unsupported", e3.kind)
  end)
end)

describe("calccas facade", function()
  it("reports the language version", function()
    assert.are.equal("1.0", calccas.LANGUAGE_VERSION)
  end)

  it("answers reserved commands with an unsupported error", function()
    for _, name in ipairs({ "diff", "solve", "factor", "integrate", "subs", "approx" }) do
      local res, err = calccas.evaluate(name .. "(x)")
      if name == "subs" then
        assert.is_nil(res)
        assert.are.equal("syntax", err.kind)
      else
        assert.is_nil(res, name)
        assert.are.equal("unsupported", err.kind, name)
        assert.is_truthy(err.message:find("reserved for a future version", 1, true))
      end
    end
  end)

  it("runs simplify and expand as parsed calls", function()
    assert.are.equal("2*x", assert(calccas.evaluate("simplify(x + x)")).text)
    assert.are.equal("x^2+2*x+1", assert(calccas.evaluate("expand((x+1)^2)")).text)
  end)

  it("does not run plot as an expression", function()
    local _, err = calccas.evaluate("plot(x)")
    assert.are.equal("unsupported", err.kind)
  end)

  it("exposes parse_program", function()
    local list = assert(calccas.parse_program("a = 1\nb = 2"))
    assert.are.equal(2, #list)
  end)
end)
