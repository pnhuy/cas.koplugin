local sizing = require("calcui.keyboard_sizing")

describe("calcui.keyboard_sizing", function()
    it("targets about 45% of the screen height in portrait", function()
        local s = sizing.compute(540, 960, 7)
        assert.is_true(s.height >= 0.35 * 960)
        assert.is_true(s.height <= 0.55 * 960)
        assert.are.equal(s.key_h * 7, s.height)
        assert.is_false(s.tight)
    end)

    it("never exceeds 55% of the height and flags tight keys in landscape", function()
        local s = sizing.compute(800, 400, 7)
        assert.is_true(s.height <= 0.55 * 400)
        assert.is_true(s.tight)
        assert.is_true(s.key_h >= 1)
    end)

    it("caps the key height on very tall screens", function()
        local s = sizing.compute(1264, 1680, 7)
        assert.is_true(s.key_h <= sizing.MAX_KEY_H)
    end)

    it("keeps the touch minimum when it fits", function()
        local s = sizing.compute(600, 800, 7)
        assert.is_true(s.key_h >= sizing.MIN_KEY_H)
        assert.is_false(s.tight)
    end)

    it("uses the compact layout under 480 px wide", function()
        assert.is_true(sizing.compute(400, 700, 7).compact)
        assert.is_false(sizing.compute(540, 720, 7).compact)
    end)

    it("leaves room for the editor above the keyboard", function()
        local s = sizing.compute(540, 720, 7)
        assert.are.equal(720 - s.height, s.free_h)
    end)

    it("rejects nonsense sizes without throwing", function()
        local s = sizing.compute(0, 0, 0)
        assert.is_true(s.key_h >= 1)
        assert.is_true(s.height >= 1)
    end)
end)
