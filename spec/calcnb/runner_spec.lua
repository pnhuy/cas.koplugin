local runner = require("calcnb.runner")
local env_mod = require("calcnb.env")
local calccas = require("calccas")

local function run(src, e)
  e = e or env_mod.new()
  return runner.run(src, e), e
end

describe("calcnb.runner", function()
  it("evaluates an expression", function()
    local o = run("1/2 + 1/3")
    assert.are.equal("value", o.kind)
    assert.are.equal("5/6", o.canonical)
  end)

  it("makes an assignment visible to later cells", function()
    local e = env_mod.new()
    local o1 = run("a = 2", e)
    assert.are.equal("value", o1.kind)
    assert.are.equal("a = 2", o1.canonical)
    local o2 = run("a^2 + 1", e)
    assert.are.equal("5", o2.canonical)
  end)

  it("shows symbolic results when a variable is unbound", function()
    local o = run("expand((x+1)^2)")
    assert.are.equal("x^2+2*x+1", o.canonical)
  end)

  it("defines and calls functions", function()
    local e = env_mod.new()
    local d = run("f(x) = x^2 + a*x", e)
    assert.are.equal("value", d.kind)
    assert.are.equal("f(x) = a*x+x^2", d.canonical)
    run("a = 3", e)
    assert.are.equal("10", run("f(2)", e).canonical)
  end)

  it("uses the last statement as the cell result", function()
    local e = env_mod.new()
    local o = run("a = 2\nb = a + 1\nb * 10", e)
    assert.are.equal("30", o.canonical)
    assert.are.equal(3, e.vars.b.n)
  end)

  it("ignores comments and blank lines", function()
    local o = run("# hi\n\n2 + 2")
    assert.are.equal("4", o.canonical)
  end)

  it("reports an empty cell", function()
    local o = run("   \n# nothing")
    assert.are.equal("value", o.kind)
    assert.is_true(o.empty)
  end)

  it("rolls the environment back when a later line fails", function()
    local e = env_mod.new()
    e:set_var("keep", 1)
    local o = run("a = 5\nb = 1/0", e)
    assert.are.equal("error", o.kind)
    assert.are.equal("div_by_zero", o.error.kind)
    assert.are.equal(2, o.error.line)
    assert.is_nil(e.vars.a)
    assert.are.equal(1, e.vars.keep)
  end)

  it("reports syntax errors with line and column", function()
    local o = run("a = 1\nsin(")
    assert.are.equal("error", o.kind)
    assert.are.equal("syntax", o.error.kind)
    assert.are.equal(2, o.error.line)
    assert.is_truthy(o.error.pos)
  end)

  it("requires assignment values to be numbers", function()
    local o = run("b = x + 1")
    assert.are.equal("error", o.kind)
    assert.are.equal("unbound_variable", o.error.kind)
  end)

  it("rejects assigning to built-in names", function()
    for _, src in ipairs({ "sin = 3", "pi = 3" }) do
      local o = run(src)
      assert.are.equal("error", o.kind, src)
      assert.are.equal("reserved", o.error.kind, src)
    end
  end)

  it("shows the engine's Not supported error for unsupported commands", function()
    local o = run("solve(x^2-4=0, x)")
    assert.are.equal("error", o.kind)
  end)

  it("plot returns a graph output", function()
    local o = run("plot(sin(x), cos(x), x=-6..6)")
    assert.are.equal("graph", o.kind)
    assert.are.equal(2, #o.graph.functions)
    assert.are.equal("sin(x)", o.graph.functions[1].label)
    assert.are.same({ lo = -6, hi = 6 }, o.graph.x_range)
    assert.is_function(calccas.compile(o.graph.functions[1].ast, "x"))
  end)

  it("plot accepts a defined function by name or call", function()
    local e = env_mod.new()
    run("f(x) = x^2", e)
    local a = run("plot(f)", e)
    local b = run("plot(f(x))", e)
    assert.are.equal("graph", a.kind)
    assert.are.equal("graph", b.kind)
    assert.are.equal(1, #a.graph.functions)
  end)

  it("plot binds defined variables", function()
    local e = env_mod.new()
    run("a = 2", e)
    local o = run("plot(a*x)", e)
    assert.are.equal("graph", o.kind)
    local fn = assert(calccas.compile(o.graph.functions[1].ast, "x"))
    assert.are.equal(6, fn(3))
  end)

  it("plot reports unknown variables", function()
    local o = run("plot(a*x)")
    assert.are.equal("error", o.kind)
    assert.are.equal("unbound_variable", o.error.kind)
  end)

  it("plot allows at most 6 functions", function()
    local o = run("plot(x,x,x,x,x,x,x)")
    assert.are.equal("error", o.kind)
    assert.are.equal("too_complex", o.error.kind)
  end)

  it("yields between statements when given a yield function", function()
    local count = 0
    local o = runner.run("a = 1\nb = 2\nc = 3", env_mod.new(), { yield = function() count = count + 1 end })
    assert.are.equal("value", o.kind)
    assert.are.equal(2, count)
  end)

  it("can be cancelled from the yield function", function()
    local e = env_mod.new()
    local o = runner.run("a = 1\nb = 2", e, { yield = function() return false end })
    assert.are.equal("error", o.kind)
    assert.are.equal("cancelled", o.error.kind)
    assert.is_nil(e.vars.a)
  end)

  it("never runs input as Lua", function()
    _G.__calcnb_pwned = nil
    run("os.execute('true')")
    run("a = (function() __calcnb_pwned = true end)()")
    assert.is_nil(_G.__calcnb_pwned)
  end)
end)

describe("calcnb.runner defined names", function()
  it("lists an assignment and a function definition", function()
    local o = run("a = 1")
    assert.are.same({ { name = "a", kind = "var" } }, o.defined)
    local f = run("f(x, y) = x + y")
    assert.are.same({ { name = "f", kind = "func", params = { "x", "y" } } }, f.defined)
  end)

  it("lists every definition of a multi-line cell once, later ones winning", function()
    local o = run("a = 1\ng(t) = t\na = 2")
    assert.are.same({
      { name = "a", kind = "var" },
      { name = "g", kind = "func", params = { "t" } },
    }, o.defined)
  end)

  it("defines nothing for expressions and plots", function()
    assert.are.same({}, run("1 + 2").defined)
    assert.are.same({}, run("plot(sin(x), x=-1..1)").defined)
    assert.are.same({}, run("").defined)
  end)

  it("gives a failing run no defined list, even when an earlier statement succeeded", function()
    local o, e = run("a = 1\nb = (")
    assert.are.equal("error", o.kind)
    assert.is_nil(o.defined)
    assert.is_nil(e.vars.a)
    local o2 = run("a = 1\nb = 1/0")
    assert.are.equal("error", o2.kind)
    assert.is_nil(o2.defined)
  end)
end)
