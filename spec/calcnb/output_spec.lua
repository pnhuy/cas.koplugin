local output = require("calcnb.output")
local calccas = require("calccas")
local errors = require("calccas.errors")

describe("calcnb.output", function()
  describe("prettify", function()
    it("turns digit exponents into superscripts", function()
      assert.are.equal("x² + 2x¹⁰", output.prettify("x^2 + 2x^10"))
      assert.are.equal("x⁻¹", output.prettify("x^-1"))
    end)

    it("turns digit subscripts into subscripts", function()
      assert.are.equal("x₁ + y₂₀", output.prettify("x_1 + y_20"))
    end)

    it("leaves complex exponents and plain text alone", function()
      assert.are.equal("x^(a+1)", output.prettify("x^(a+1)"))
      assert.are.equal("x^y", output.prettify("x^y"))
      assert.are.equal("a_b", output.prettify("a_b"))
    end)

    it("shows the constant pi as π but not inside words", function()
      assert.are.equal("2*π", output.prettify("2*pi"))
      assert.are.equal("pivot", output.prettify("pivot"))
    end)
  end)

  describe("value", function()
    it("keeps canonical text separate from display text", function()
      local o = output.value(assert(calccas.evaluate("expand((x+1)^2)")))
      assert.are.equal("value", o.kind)
      assert.are.equal("x^2+2*x+1", o.canonical)
      assert.are.equal("x²+2*x+1", o.display)
      assert.is_false(o.truncated)
    end)

    it("canonical text re-parses to the same value", function()
      for _, src in ipairs({ "1/2", "sqrt(2)", "pi", "0.5+0.25", "sin(1)" }) do
        local o = output.value(assert(calccas.evaluate(src)))
        local again = assert(calccas.evaluate(o.canonical))
        assert.are.equal(again.text, assert(calccas.evaluate(src)).text, src)
      end
    end)

    it("keeps the approximation in the display text", function()
      local o = output.value(assert(calccas.evaluate("sqrt(2)")))
      assert.are.equal("sqrt(2)", o.canonical)
      assert.is_truthy(o.display:find("≈", 1, true))
    end)

    it("truncates long display text and keeps the full text", function()
      local long = string.rep("x", 700)
      local o = output.text(long)
      assert.is_true(o.truncated)
      assert.is_true(#o.display <= 604)
      assert.are.equal(long, o.full)
      assert.are.equal(long, o.canonical)
    end)

    it("never cuts a multi-byte character in half", function()
      local o = output.text(string.rep("²", 400))
      assert.is_true(o.truncated)
      assert.are.equal(0, #o.display:gsub("²", "") - #"…")
    end)
  end)

  describe("error", function()
    it("wraps an engine error with the line", function()
      local o = output.error(errors.new("syntax", "unexpected ')'", 4), 2)
      assert.are.equal("error", o.kind)
      assert.are.equal("syntax", o.error.kind)
      assert.are.equal(4, o.error.pos)
      assert.are.equal(2, o.error.line)
    end)

    it("accepts plain {kind, message} tables from the statement layer", function()
      local o = output.error({ kind = "reserved", message = "Name is reserved", line = 3 })
      assert.are.equal("reserved", o.error.kind)
      assert.are.equal(3, o.error.line)
    end)
  end)

  describe("graph", function()
    it("keeps functions and the range", function()
      local node = assert(calccas.parse("sin(x)"))
      local o = output.graph({ { label = "sin(x)", ast = node } }, { lo = -6, hi = 6 })
      assert.are.equal("graph", o.kind)
      assert.are.equal(1, #o.graph.functions)
      assert.are.same({ lo = -6, hi = 6 }, o.graph.x_range)
      assert.are.equal("sin(x)", o.canonical)
    end)

    it("allows at most 6 functions", function()
      local node = assert(calccas.parse("x"))
      local fns = {}
      for i = 1, 7 do
        fns[i] = { label = "x", ast = node }
      end
      local o, err = output.graph(fns)
      assert.is_nil(o)
      assert.are.equal("too_complex", err.kind)
    end)
  end)
end)
