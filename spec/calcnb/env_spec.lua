local env = require("calcnb.env")
local calccas = require("calccas")

describe("calcnb.env", function()
  it("stores and returns variables", function()
    local e = env.new()
    assert.is_true(e:set_var("a", 2))
    assert.are.equal(2, e.vars.a)
  end)

  it("stores functions and exposes them for the engine", function()
    local e = env.new()
    local body = assert(calccas.parse("x^2"))
    assert.is_true(e:set_func("f", "x", body))
    assert.are.equal("x", e.funcs.f.param)
    assert.are.equal(body, e.funcs.f.body)
  end)

  it("rejects reserved names", function()
    local e = env.new()
    for _, name in ipairs({ "sin", "pi", "e", "plot", "simplify", "expand" }) do
      local ok, err = e:set_var(name, 1)
      assert.is_false(ok, name)
      assert.are.equal("reserved", err.kind)
    end
  end)

  it("lets a name be a variable or a function, not both", function()
    local e = env.new()
    e:set_var("f", 1)
    e:set_func("f", "x", assert(calccas.parse("x")))
    assert.is_nil(e.vars.f)
    e:set_var("f", 3)
    assert.is_nil(e.funcs.f)
  end)

  it("caps the number of names at 100", function()
    local e = env.new()
    for i = 1, 100 do
      assert.is_true(e:set_var("v" .. i, i))
    end
    local ok, err = e:set_var("extra", 1)
    assert.is_false(ok)
    assert.are.equal("too_complex", err.kind)
    assert.is_true(e:set_var("v1", 99)) -- replacing is still fine
  end)

  it("snapshots and restores", function()
    local e = env.new()
    e:set_var("a", 1)
    local snap = e:snapshot()
    e:set_var("a", 2)
    e:set_var("b", 3)
    e:set_func("f", "x", assert(calccas.parse("x")))
    e:restore(snap)
    assert.are.equal(1, e.vars.a)
    assert.is_nil(e.vars.b)
    assert.is_nil(e.funcs.f)
  end)

  it("a snapshot is not changed by later edits", function()
    local e = env.new()
    e:set_var("a", 1)
    local snap = e:snapshot()
    e:set_var("a", 5)
    e:restore(snap)
    e:set_var("a", 7)
    e:restore(snap)
    assert.are.equal(1, e.vars.a)
  end)

  it("reports whether a name is defined and lists names sorted", function()
    local e = env.new()
    e:set_var("b", 1)
    e:set_func("a", "x", assert(calccas.parse("x")))
    assert.are.same({ "a", "b" }, e:names())
    assert.is_true(e:has("a"))
    assert.is_false(e:has("c"))
  end)

  it("clears everything", function()
    local e = env.new()
    e:set_var("a", 1)
    e:clear()
    assert.are.same({}, e:names())
  end)
end)

describe("calcnb.env version", function()
  it("bumps the version only when a definition changes", function()
    local e = env.new()
    assert.are.equal(0, e.version)
    e:set_var("a", 1)
    assert.are.equal(1, e.version)
    e:set_var("a", 1)
    assert.are.equal(1, e.version)
    e:set_var("a", 2)
    assert.are.equal(2, e.version)
  end)

  it("compares engine number nodes and functions by value", function()
    local calc = require("calccas")
    local e = env.new()
    e:set_var("a", assert(calc.evaluate("1/2")).exact)
    local v = e.version
    e:set_var("a", assert(calc.evaluate("2/4")).exact)
    assert.are.equal(v, e.version)
    e:set_func("f", "x", assert(calc.parse("x+1")))
    v = e.version
    e:set_func("f", "x", assert(calc.parse("1+x")))
    assert.are.equal(v, e.version)
    e:set_func("f", "x", assert(calc.parse("x+2")))
    assert.are.equal(v + 1, e.version)
  end)

  it("restores the version with a snapshot", function()
    local e = env.new()
    e:set_var("a", 1)
    local snap = e:snapshot()
    e:set_var("a", 2)
    e:restore(snap)
    assert.are.equal(1, e.version)
  end)
end)
