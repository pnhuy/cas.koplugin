local run_queue = require("calcnb.run_queue")

describe("calcnb.run_queue", function()
    it("hands out cells in order, one at a time", function()
        local q = run_queue.new()
        assert.is_true(q:start({ 1, 2, 3 }))
        assert.are.equal(1, q:next())
        assert.is_true(q:busy())
        q:done()
        assert.are.equal(2, q:next())
        q:done()
        assert.are.equal(3, q:next())
        q:done()
        assert.is_nil(q:next())
        assert.is_false(q:busy())
    end)

    it("rejects a second request while busy", function()
        local q = run_queue.new()
        q:start({ 1, 2 })
        local ok, err = q:start({ 9 })
        assert.is_nil(ok)
        assert.are.equal("busy", err)
        assert.are.equal(1, q:next())
    end)

    it("stays busy while the current cell has not finished", function()
        local q = run_queue.new()
        q:start({ 1 })
        q:next()
        assert.is_true(q:busy())
        q:done()
        assert.is_false(q:busy())
    end)

    it("accepts a new request after the queue drains", function()
        local q = run_queue.new()
        q:start({ 1 })
        q:next()
        q:done()
        assert.is_true(q:start({ 2 }))
    end)

    it("does not stop at an error: later cells are still handed out", function()
        local q = run_queue.new()
        q:start({ 1, 2 })
        q:next()
        q:done() -- the caller records the error on the cell; the queue does not care
        assert.are.equal(2, q:next())
    end)

    it("cancels everything that has not started", function()
        local q = run_queue.new()
        q:start({ 1, 2, 3 })
        q:next()
        q:cancel()
        assert.is_true(q:cancelled())
        q:done()
        assert.is_nil(q:next())
        assert.is_false(q:busy())
        assert.is_true(q:start({ 4 }))
        assert.is_false(q:cancelled())
    end)

    it("reports how many cells are waiting", function()
        local q = run_queue.new()
        q:start({ 1, 2, 3 })
        assert.are.equal(3, q:pending())
        q:next()
        assert.are.equal(2, q:pending())
    end)

    it("ignores an empty request", function()
        local q = run_queue.new()
        assert.is_true(q:start({}))
        assert.is_false(q:busy())
    end)
end)
